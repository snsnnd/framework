# Generate 24x24 Chinese glyph bitmaps for the LCD (from simhei.ttf).
# Output: hwtest_g431/font_cn.h  (const uint8_t CN_Glyphs[N][72] + codepoint map)
from PIL import Image, ImageDraw, ImageFont
import json

CHARS = "游戏结束最高分新纪录按B1开始再来飞菜单"
SIZE = 24
FONT = "C:/Windows/Fonts/simhei.ttf"

font = ImageFont.truetype(FONT, 22)
glyphs = []
cps = []
for ch in CHARS:
    img = Image.new("L", (SIZE, SIZE), 0)
    d = ImageDraw.Draw(img)
    bbox = d.textbbox((0, 0), ch, font=font)
    w = bbox[2] - bbox[0]
    h = bbox[3] - bbox[1]
    d.text(((SIZE - w) // 2 - bbox[0], (SIZE - h) // 2 - bbox[1]), ch, font=font, fill=255)
    img = img.transpose(Image.FLIP_LEFT_RIGHT)   # 屏幕列方向与字模相反，需水平镜像
    px = img.load()
    data = bytearray()
    for r in range(SIZE):
        for b in range(SIZE // 8):
            byte = 0
            for c in range(8):
                col = b * 8 + c
                if px[col, r] > 100:
                    byte |= 0x80 >> c
            data.append(byte)
    glyphs.append(bytes(data))
    cps.append(ord(ch))

with open("D:/framework/hwtest_g431/font_cn.h", "w", encoding="ascii") as f:
    f.write("/* 24x24 Chinese glyphs (simhei) - generated by gen_font_cn.py */\n")
    f.write("#ifndef FONT_CN_H\n#define FONT_CN_H\n#include <stdint.h>\n\n")
    f.write(f"#define CN_GLYPH_N {len(cps)}\n\n")
    f.write("/* codepoints of the glyphs, in order */\n")
    f.write("static const uint16_t CN_CP[CN_GLYPH_N] = {")
    f.write(", ".join(f"0x{cp:04X}" for cp in cps))
    f.write("};\n\n")
    f.write("static const uint8_t CN_Glyphs[CN_GLYPH_N][72] = {\n")
    for cp, g in zip(cps, glyphs):
        f.write("    { /* U+%04X */\n    " % cp)
        f.write(",".join(f"0x{b:02X}" for b in g))
        f.write("\n    },\n")
    f.write("};\n\n#endif\n")
print(f"OK: {len(cps)} glyphs -> font_cn.h")

