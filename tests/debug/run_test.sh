./build/debug_perf_test 2>&1 | tee "${RESULTS_DIR}/test_output.txt"

# 复制结果文件
if [ -f "tests/debug/perf_results.csv" ]; then
    cp "tests/debug/perf_results.csv" "${RESULTS_DIR}/"
fi

if [ -f "tests/debug/perf_results.json" ]; then
    cp "tests/debug/perf_results.json" "${RESULTS_DIR}/"
fi

