/**
 * @file    ultrasonic.h
 * @brief   超声波距离传感器的标准化数据结构
 *
 * =========================================================================
 * 超声波传感器是什么？
 * =========================================================================
 *
 *   超声波传感器通过发射 40kHz 的超声波脉冲，并测量回波返回的时间，
 *   来计算到目标的距离。原理类似于蝙蝠的回声定位。
 *
 *   计算公式：
 *     distance = (声速 × 回波时间) / 2
 *     除以 2 是因为声波走了"发射→目标→接收"的往返路径
 *     声速 ≈ 340 m/s (15°C 空气中)，温度变化会影响精度
 *
 *   典型芯片/模块：
 *     - HC-SR04 (最常见，Trig/Echo 接口，2cm~4m 量程)
 *     - US-100 (UART/PWM 接口，自带温度补偿)
 *     - JSN-SR04T (防水型，水下测距)
 *
 *   局限性：
 *     - 测量盲区：距离太近 (<2cm) 时回波与发射波重叠，无法测量
 *     - 软表面吸音：布料、泡沫等材料反射弱，测量不可靠
 *     - 窄波束角：通常 ~15°，只能检测正前方的物体
 *     - 多路径反射：复杂环境中可能收到多个回波，取第一个
 *
 *   典型应用：
 *     - 小车避障（检测前方障碍物距离）
 *     - 液位测量（测水面/油面高度）
 *     - 停车辅助（倒车雷达）
 *
 * =========================================================================
 * 数据字段
 * =========================================================================
 *
 *   distance_m — 距离值，单位：米 (m)
 *                例如 0.5 = 50cm, 2.3 = 2.3m
 *                efw_ultrasonic_data_t 只有一个字段，
 *                为的是保持各传感器类型接口一致（都通过 read 返回结构体）
 */

#ifndef EFW_SENSOR_ULTRASONIC_H
#define EFW_SENSOR_ULTRASONIC_H

#include "efw/core/common.h"

/**
 * @brief 超声波距离传感器数据结构
 *
 * @field distance_m 测量距离 (单位：米 m)
 *                   典型范围：0.02 ~ 4.0 (HC-SR04)
 *                   值为负或 0 可能表示测量失败/超时/超出量程
 */
typedef struct {
    float distance_m;       /**< 测量距离 (米) */
} efw_ultrasonic_data_t;

/**
 * @brief 读取超声波传感器数据
 *
 * 内部委托给通用 efw_sensor_read()。
 * 用户需要在注册的超声波传感器的 read 回调中触发测量并填充 distance_m。
 *
 * 注意：超声波传感器通常需要数百微秒到数十毫秒才能完成一次测量
 * （声速约 340m/s，测 4m 需要约 23ms 往返时间）。
 * 如果 read 回调是阻塞等待的，注意不要在高速控制循环中调用。
 * 推荐方案：使用中断/DMA 在后台触发测量，read 仅读取已完成的结果。
 *
 * @param name 传感器注册名称 (如 "ultrasonic_front", "ultrasonic_left")
 * @param out  输出数据指针 (efw_ultrasonic_data_t*，不能为空)
 * @return EFW_OK 成功, EFW_ERR_INVALID 参数错误
 */
efw_status_t efw_ultrasonic_read(const char *name, efw_ultrasonic_data_t *out);

#endif
