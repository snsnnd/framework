/**
 * @file    app_components.c
 * @brief   组件层实现 —— 创建并注册循迹 PID 控制器
 *
 * 本文件创建了一个 PD 控制器用于循迹转向控制。
 *
 * =========================================================================
 * PID 参数配置 (循迹场景)
 * =========================================================================
 *
 *   Kp=18.0, Ki=0.0, Kd=2.5, 限幅=±60
 *
 *   这是一个 PD 控制器 (无积分项)：
 *     - Kp=18.0 较大 → 对黑线偏差响应灵敏，弯道跟得上
 *       Kp 太小 → 弯道转向不足 (车冲出赛道)
 *       Kp 太大 → 直道来回摇摆 (振荡)
 *
 *     - Ki=0.0 禁用积分 → 循迹场景不需要积分
 *       黑线位置持续变化，积分只会累积错误的修正量，导致过弯后失控
 *
 *     - Kd=2.5 较强微分 → 抑制直道高频振荡
 *       Kd 太小 → 直道上小车左右摇摆 (蛇形走位)
 *       Kd 太大 → 对传感器噪声敏感，电机可能高频微调产生啸叫
 *
 *     - 限幅 ±60 → 最大差速不超过基础速度 45
 *       公式: left=base_speed-turn, right=base_speed+turn
 *       当 turn_max=60, base=45 → speed 范围 [-15, 105]
 *       turn_max < base_speed 确保正常情况下不会反转
 *
 * =========================================================================
 * 参数调节方法
 * =========================================================================
 *
 *   第1步：Kd=0，增大 Kp 直到直道开始出现轻微摇摆
 *   第2步：加入 Kd (从 0.5 开始)，增大到直道摇摆消失
 *   第3步：在弯道测试——如果转向不够，增大 Kp；
 *          如果直道又摇摆了，增大 Kd
 *   第4步：反复微调达到最佳平衡
 *
 *   口诀：Kp 管弯道，Kd 管直道
 */

#include "app_components.h"
#include "app_manifest.h"

/**
 * @brief 循迹 PID 实例 —— PD 控制器 (Ki=0)
 *
 * 每个控制回路需要一个独立的 efw_pid_t 实例。
 * 如果项目中有舵机转向，可能需要另一个 PID 实例 (参数会不同)。
 */
static efw_pid_t g_line_pid = {
    .kp = 18.0f,            /**< 比例系数：弯道响应强度 */
    .ki = 0.0f,             /**< 积分系数：循迹场景设为 0 (不使用积分) */
    .kd = 2.5f,             /**< 微分系数：直道防摇摆阻尼 */
    .kff = 0.0f,
    .integral_min = -20.0f,
    .integral_max = 20.0f,
    .out_min = -60.0f,      /**< 输出下限：最大左转差速 (负值 = 左转) */
    .out_max = 60.0f,       /**< 输出上限：最大右转差速 (正值 = 右转) */
    .anti_windup = 1,
};

/**
 * @brief PID 算法注册条目
 *
 * name="line_pid" — 应用层通过此名称引用
 * type=EFW_ALGO_CONTROL — 控制类算法
 * run=efw_pid_run — 使用框架内置的 PID 执行函数
 */
static efw_algo_ops_t g_line_pid_algo = {
    .name = APP_LINE_PID_NAME,       /**< 算法名称 (应用层通过此名引用) */
    .type = EFW_ALGO_CONTROL,       /**< 类型：控制算法 */
    .ctx = &g_line_pid,             /**< 上下文：指向 efw_pid_t 实例 */
    .run = efw_pid_run,             /**< 执行函数：框架内置 PID */
};

/**
 * @brief 注册组件层所有算法实例
 *
 * 目前仅注册一个 PID 实例。如需添加更多 (如速度 PID、陀螺仪滤波)，
 * 在此函数中追加对应的 efw_algo_register() 调用。
 */
efw_status_t app_components_register(void) {
    return efw_algo_register(&g_line_pid_algo);  /* 注册循迹 PID */
}
