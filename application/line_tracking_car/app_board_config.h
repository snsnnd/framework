/**
 * @file    app_board_config.h
 * @brief   板级硬件配置 —— 将框架组件映射到物理引脚、外设和运行参数
 *
 * 本文件是项目中唯一需要根据实际硬件修改的配置文件。
 * 它定义了：
 *   ① 循迹传感器的物理 GPIO 引脚映射
 *   ② 左右电机的 PWM 通道和方向引脚映射
 *   ③ 控制算法的运行参数（基础速度、限速、控制周期）
 *
 * =========================================================================
 * 设计原则：配置与逻辑分离
 * =========================================================================
 *
 *   换一块 PCB 板、换一个 MCU 型号、换一种电机驱动模块时，
 *   只需要修改本文件，不需要动任何业务逻辑代码。
 *   app_platform.c 通过本文件的宏来初始化硬件上下文，
 *   不直接硬编码引脚号。
 *
 * =========================================================================
 * 引脚配置说明
 * =========================================================================
 *
 * 【循迹传感器引脚 APP_LINE_PINS[]】
 *   5 路数字循迹传感器的输入引脚，每路对应一个 GPIO。
 *   格式：{ GPIO端口, 引脚号 }
 *   例如 {APP_GPIO_PORT_A, 0u} 表示 PA0
 *
 *   真实项目中循迹传感器通常是：
 *     - 模拟量：接 ADC 通道 → HAL type=EFW_HAL_ADC
 *     - 数字量：接 GPIO 输入 → HAL type=EFW_HAL_GPIO（本示例采用此方案）
 *       数字量来自比较器（如 LM393）将模拟信号阈值化后的 0/1 输出
 *       APP_LINE_ACTIVE_VALUE 定义检测到黑线时的电平（1=高有效, 0=低有效）
 *
 * 【电机 PWM 和方向引脚】
 *   每个电机需要两个信号：
 *     PWM 通道：控制转速（占空比 0~100%）
 *       格式：{ 定时器ID, 通道号 }
 *       例如 {1u, 1u} 表示 TIM1_CH1
 *     方向引脚：控制转向（GPIO 高低电平）
 *       例如 {APP_GPIO_PORT_B, 0u} 表示 PB0
 *
 * =========================================================================
 * 运行参数说明
 * =========================================================================
 *
 *   APP_LINE_ACTIVE_VALUE — 循迹传感器"检测到线"的电平 (0 或 1)
 *     1 = 高电平有效 (检测到黑线时输出高电平)
 *     0 = 低电平有效 (检测到黑线时输出低电平)
 *     取决于比较器模块的设计（LM393 可选同相/反相输出）
 *
 *   APP_LINE_BASE_SPEED (65.0) — 基础巡航速度
 *     直线行驶时左右轮的共同速度。
 *     值越大车越快，但留给转弯的"速度裕量"越小。
 *     注意：base_speed 必须 > PID.out_max (60)，否则一轮会反转。
 *     65 > 60 ✓ 满足约束（最小速度 5，不会反转）
 *
 *   APP_LINE_MIN_SPEED (0.0) — 最小速度限制
 *     防止差速公式计算出负速度导致电机反转。
 *     设为 0 表示允许的最低速度为 0（停止），不允许反转。
 *
 *   APP_LINE_MAX_SPEED (100.0) — 最大速度限制
 *     防止 PID 输出叠加上 base_speed 后超出电机物理极限。
 *     设为 100 对应 PWM 100% 占空比。
 *
 *   APP_LINE_DT_SECONDS (0.001f) — 控制周期
 *     1ms = 0.001s，对于循迹小车来说是合适的控制频率。
 *     电机响应时间通常 10~100ms，1ms 控制周期远快于机械响应，
 *     确保控制指令始终领先于物理状态。
 */

#ifndef APP_BOARD_CONFIG_H
#define APP_BOARD_CONFIG_H

#include <stdint.h>

/* ==================================================================
 *  第1部分：传感器通道数
 * ================================================================== */

/** @brief 循迹传感器通道数 (默认 5，可通过 -D 覆写) */
#ifndef APP_LINE_CHANNELS
#define APP_LINE_CHANNELS 5
#endif

/* ==================================================================
 *  第2部分：硬件抽象数据类型
 * ================================================================== */

/**
 * @brief GPIO 引脚描述符
 *
 * @field port GPIO 端口号 (如 APP_GPIO_PORT_A = 0 = GPIOA)
 * @field pin  引脚号 (0~15)
 */
typedef struct {
    uint8_t port;       /**< GPIO 端口 (APP_GPIO_PORT_A/B/C) */
    uint16_t pin;       /**< 引脚编号 (0~15) */
} app_gpio_pin_t;

/**
 * @brief PWM 通道描述符
 *
 * @field timer_id 定时器编号 (如 1=TIM1, 2=TIM2)
 * @field channel  通道号 (1~4，对应 TIMx_CH1 ~ CH4)
 */
typedef struct {
    uint8_t timer_id;   /**< 定时器 ID (1=TIM1, 2=TIM2, ...) */
    uint8_t channel;    /**< PWM 通道号 (1~4) */
} app_pwm_channel_t;

/* ==================================================================
 *  第3部分：GPIO 端口常量
 * ================================================================== */

#define APP_GPIO_PORT_A 0u   /**< GPIOA 端口标识 */
#define APP_GPIO_PORT_B 1u   /**< GPIOB 端口标识 */
#define APP_GPIO_PORT_C 2u   /**< GPIOC 端口标识 */

/* ==================================================================
 *  第4部分：循迹传感器引脚分配
 *
 *  5 路传感器从左到右依次排列，分别接到 PA0~PA4。
 *  修改方法：改变每行的 {端口, 引脚} 对即可。
 *  如果传感器数量不是 5，修改 APP_LINE_CHANNELS 并同步增减数组元素。
 * ================================================================== */

/** @brief 5 路循迹传感器引脚映射 (PA0 ~ PA4) */
static const app_gpio_pin_t APP_LINE_PINS[APP_LINE_CHANNELS] = {
    { APP_GPIO_PORT_A, 0u },   /**< 通道0 (最左)  → PA0 */
    { APP_GPIO_PORT_A, 1u },   /**< 通道1 (左偏)  → PA1 */
    { APP_GPIO_PORT_A, 2u },   /**< 通道2 (中心)  → PA2 */
    { APP_GPIO_PORT_A, 3u },   /**< 通道3 (右偏)  → PA3 */
    { APP_GPIO_PORT_A, 4u },   /**< 通道4 (最右)  → PA4 */
};

/* ==================================================================
 *  第5部分：电机 PWM 和方向引脚分配
 * ================================================================== */

/** @brief 左电机 PWM 通道：TIM1_CH1 */
#define APP_LEFT_MOTOR_PWM   { 1u, 1u }

/** @brief 右电机 PWM 通道：TIM1_CH2 */
#define APP_RIGHT_MOTOR_PWM  { 1u, 2u }

/** @brief 左电机方向引脚：PB0 */
#define APP_LEFT_MOTOR_DIR   { APP_GPIO_PORT_B, 0u }

/** @brief 右电机方向引脚：PB1 */
#define APP_RIGHT_MOTOR_DIR  { APP_GPIO_PORT_B, 1u }

/* ==================================================================
 *  第6部分：运行参数
 * ================================================================== */

/**
 * @brief 循迹传感器"检测到黑线"的有效电平
 *
 * 1 = 高电平表示检测到黑线 (模拟比较器同相输出)
 * 0 = 低电平表示检测到黑线 (模拟比较器反相输出)
 * 具体取决于硬件上 LM393 等比较器的输出极性配置
 */
#define APP_LINE_ACTIVE_VALUE 1u

/**
 * @brief 基础巡航速度 (65.0)
 *
 * 直线行驶时左右轮共同速度。
 * 约束：必须 > PID.out_max (60)，否则 turn=60 时一轮会反转。
 */
#define APP_LINE_BASE_SPEED   65.0f

/**
 * @brief 最小速度限制 (0.0)
 *
 * 防止差速后速度小于 0 导致电机反转。
 * 设为 0 = 最低允许停止，不允许反转。
 */
#define APP_LINE_MIN_SPEED    0.0f

/**
 * @brief 最大速度限制 (100.0)
 *
 * 防止差速后速度超过电机/PWM 的物理上限。
 * 100.0 对应 PWM 100% 占空比。
 */
#define APP_LINE_MAX_SPEED    100.0f

/**
 * @brief 控制周期 (0.001 秒 = 1ms)
 *
 * PID 计算和电机指令更新的时间间隔。
 * 1ms 对于循迹小车来说足够快（电机机械响应 > 10ms）。
 */
#define APP_LINE_DT_SECONDS   0.001f

#endif
