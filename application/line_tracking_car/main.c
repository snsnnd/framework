/**
 * @file    main.c
 * @brief   循迹小车 —— 程序入口
 *
 * 本文件是完整循迹小车应用程序的入口点。
 *
 * =========================================================================
 * 程序流程
 * =========================================================================
 *
 *   ① app_init()                    — 初始化框架 + 注册全部硬件和算法 + 绑定 handle
 *   ② 设置模拟数字循迹状态          — 模拟 5 路传感器的 0/1 输出
 *   ③ app_loop_1ms()                — 执行一次完整的控制循环
 *
 * =========================================================================
 * 模拟的传感器数据
 * =========================================================================
 *
 *   centered_line = {100, 500, 1000, 500, 100}
 *
 *   这是 5 通道的模拟读数，分布关于中心对称：
 *     通道 0: 100   (最左 → 低值，黑线偏左)
 *     通道 1: 500   (左偏)
 *     通道 2: 1000  (中心 → 最高值 = 最白，黑线不在中心下方)
 *     通道 3: 500   (右偏)
 *     通道 4: 100   (最右 → 低值)
 *
 *   由于分布对称 (100-500-1000-500-100)，加权误差 ≈ 0。
 *   PID 输出 ≈ 0，左右轮等速 → 直行。
 *
 *   要测试偏移情况，改为不对称分布，例如：
 *     {100, 1000, 500, 500, 100} → 通道 1 很亮 (白)，黑线偏右 → error>0 → 车右转
 *
 * =========================================================================
 * 三层架构调用关系
 * =========================================================================
 *
 *   main()
 *     └─ app_init()
 *          ├─ efw_init()                     ← 初始化 7 个注册表
 *          ├─ app_platform_register()        ← 注册 ADC/传感器/电机
 *          └─ app_components_register()      ← 注册 PID
 *     └─ app_platform_set_line_state()      ← 设置模拟 0/1 循迹状态
 *     └─ app_loop_1ms()                ← 执行控制循环，无字符串查找
 */

#include "app_bootstrap.h"
#include "app_platform.h"

int main(void) {
    /** 模拟的 5 通道数字循迹状态：1 表示该路检测到线 */
    const uint16_t centered_line[APP_LINE_CHANNELS] = { 0, 0, 1, 0, 0 };

    /* ① 初始化：框架 → 平台 → 组件 */
    app_init();

    /* ② 设置模拟数字循迹状态 */
    app_platform_set_line_state(centered_line);

    /* ③ 执行一次完整的控制循环 (真实项目中在 1ms 定时器中断中调用) */
    app_loop_1ms();

    return 0;
}
